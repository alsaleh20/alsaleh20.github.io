const langMapping = {
    'ar': 'العربية',
    'en': 'English',
    'tr': 'Türkçe'
};

let currentLang = localStorage.getItem('sys_lang') || 'ar';

function switchLang(lang) {
    if (!langMapping[lang]) return;

    currentLang = lang;
    localStorage.setItem('sys_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar') ? 'rtl' : 'ltr';

    const dashboardContainer = document.querySelector('.dashboard-container');
    if (dashboardContainer) {
        dashboardContainer.style.direction = (lang === 'ar') ? 'rtl' : 'ltr';
    }

    // Apply translations
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[key] && translations[key][lang]) {
            el.innerHTML = translations[key][lang];
        }
    });

    // Dispatch global event for specific script triggers (like dashboard button logic)
    document.dispatchEvent(new CustomEvent('langChanged', { detail: lang }));
}

function initGlassmorphismLangSwitcher(containerSelector) {
    const container = document.querySelector(containerSelector);
    if (!container) return;

    const switcherHTML = `
        <div class="lang-switcher-wrapper" style="position: relative; display: inline-block; font-family: inherit;">
            <button class="lang-switcher-btn" style="background: rgba(255,255,255,0.05); color: white; border: 1px solid var(--glass-border, rgba(255,255,255,0.1)); padding: 8px 15px; border-radius: 8px; cursor: pointer; display: flex; align-items: center; gap: 8px; font-size: 0.9rem; backdrop-filter: blur(10px); transition: background 0.3s ease;">
                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><circle cx="12" cy="12" r="10"></circle><path d="M2 12h20"></path><path d="M12 2a15.3 15.3 0 0 1 4 10 15.3 15.3 0 0 1-4 10 15.3 15.3 0 0 1-4-10 15.3 15.3 0 0 1 4-10z"></path></svg>
                <span id="currentLangLabel">${langMapping[currentLang]}</span>
                <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M6 9l6 6 6-6"></path></svg>
            </button>
            <div class="lang-switcher-dropdown" style="display: none; position: absolute; top: calc(100% + 5px); right: 0; background: rgba(10, 5, 18, 0.9); border: 1px solid var(--glass-border, rgba(255,255,255,0.1)); border-radius: 8px; backdrop-filter: blur(20px); min-width: 150px; z-index: 1000; overflow: hidden; box-shadow: 0 10px 30px rgba(0,0,0,0.5);">
                ${Object.keys(langMapping).map(key => `
                    <div class="lang-option" data-lang="${key}" style="padding: 10px 15px; cursor: pointer; transition: background 0.2s; color: ${key === currentLang ? 'var(--accent-orange, #ff501a)' : 'white'};">
                        ${langMapping[key]}
                    </div>
                `).join('')}
            </div>
        </div>
    `;

    container.innerHTML = switcherHTML;

    const wrapper = container.querySelector('.lang-switcher-wrapper');
    const btn = wrapper.querySelector('.lang-switcher-btn');
    const dropdown = wrapper.querySelector('.lang-switcher-dropdown');
    const options = wrapper.querySelectorAll('.lang-option');

    btn.addEventListener('click', (e) => {
        e.stopPropagation();
        dropdown.style.display = dropdown.style.display === 'none' ? 'block' : 'none';
    });

    document.addEventListener('click', () => {
        dropdown.style.display = 'none';
    });

    options.forEach(opt => {
        opt.addEventListener('click', (e) => {
            const lang = e.target.getAttribute('data-lang');
            switchLang(lang);

            // update UI label
            wrapper.querySelector('#currentLangLabel').innerText = langMapping[lang];

            // update highlighting
            options.forEach(o => o.style.color = 'white');
            e.target.style.color = 'var(--accent-orange, #ff501a)';
        });
    });

    // Injected styles for hover effects safely
    if (!document.getElementById('lang-switcher-css')) {
        const style = document.createElement('style');
        style.id = 'lang-switcher-css';
        style.innerHTML = `
            .lang-option:hover { background: rgba(255,255,255,0.1); }
            .lang-switcher-btn:hover { background: rgba(255,255,255,0.15) !important; }
        `;
        document.head.appendChild(style);
    }
}

document.addEventListener('DOMContentLoaded', () => {
    switchLang(currentLang);
});
